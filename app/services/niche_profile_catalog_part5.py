def _questions(q, item: dict[str, Any]):
    return [
        q(
            "specialization",
            item["primary_label"],
            "multiple_choice",
            item["offer_examples"],
        ),
        q(
            "target_type",
            "Кого искать?",
            "multiple_choice",
            item["target_options"],
        ),
        q(
            "lead_signals",
            "Какие признаки показывают, что клиенту нужна ваша услуга?",
            "multiple_choice",
            item["pain_signals"],
        ),
        q(
            "location",
            "В каком городе, регионе или стране искать?",
            "text",
        ),
        q(
            "priority_pains",
            "Какие проблемы клиента приоритетны?",
            "multiple_choice",
            item["pain_signals"],
        ),
        q(
            "required_contacts",
            "Какие контакты обязательны?",
            "multiple_choice",
            ["Телефон", "Telegram", "Email", "Сайт", "Соцсети"],
        ),
        q(
            "service_format",
            "Какой формат работы вы предлагаете?",
            "single_choice",
            ["Разовая услуга", "Проект", "Ежемесячное сопровождение", "Консультация"],
        ),
        q(
            "minimum_budget",
            "Какой минимальный бюджет клиента подходит?",
            "number",
            required=False,
        ),
        q(
            "exclusions",
            "Каких клиентов, отрасли или источники исключать?",
            "text",
            required=False,
        ),
        q(
            "entry_offer",
            "Что вы предлагаете клиенту первым шагом?",
            "text",
        ),
    ]


def build_part5_catalog(ProfileDefinition, q):
    definitions = []
    for item in PROFILE_SPECS_PART5:
        config = {
            "positive_keywords": list(item["positive_keywords"]),
            "default_exclusions": list(item["default_exclusions"]),
            "pain_signals": list(item["pain_signals"]),
            "offer_examples": list(item["offer_examples"]),
        }
        definitions.append(
            ProfileDefinition(
                category_code=item["category_code"],
                code=item["code"],
                name=item["name"],
                description=item["description"],
                seller_label=item["seller_label"],
                target_label=item["target_label"],
                config=config,
                questions=_questions(q, item),
            )
        )
    return list(CATEGORIES_PART5), definitions


def build_part5_pain_rules(PainRule):
    result = {}
    for profile_code, rows in PAIN_RULE_SPECS_PART5.items():
        result[profile_code] = tuple(
            PainRule(
                label=label,
                patterns=tuple(patterns),
                offer=offer,
            )
            for label, patterns, offer in rows
        )
    return result
